"""RELEASE PIPELINE PROOF: does merged code reach the trading box on its own, and how fast?

    python scripts/release_pipeline_proof.py --repo OWNER/NAME           # writes the report
    python scripts/release_pipeline_proof.py --repo OWNER/NAME --print   # stdout only

Writes desks/mt5/reports/RELEASE_PIPELINE_PROOF.json (box state, published with the box's state
commits) and appends one line per run to RELEASE_PIPELINE_PROOF_HISTORY.jsonl. Run hourly by
scripts/merge_pipeline_watch.py (itself run by Quant-WorkflowGate every 10 min), so it adds no
scheduled task: one scheduler, one more read-only reader.

WHY (zuck). "Make all done ASAP: releases, landings, everything -- adopt new code ASAP; the hourly
pass monitors adoption speed" (10-21, 11-04), and the FINAL AUTONOMY DIRECTIVE (11-13) items 8
and 10: "ensure releases are automatically verified, merged, sealed and adopted by the VPS" and
"prove autonomy through two consecutive automatic deployments and a 24-hour unattended operating
test". merge_pipeline_watch.py puts a clock on everything BEFORE the merge; nothing put a clock on
what happens AFTER it, so a merged fix could sit un-adopted for days (11-10 to 11-13: the box ran
an unsealed tree and adopted nothing) while every merge-side signal was green.

THE FOUR STAGES, per PR merged into LIVE in the lookback (default 7 days):

    merged     the PR's merge commit on LIVE, and HOW it merged:
                 AUTO      the gate's no-comment AUTO/LOW title ("Merge #N (AUTO tier, ...")
                 REGISTRY  the gate's box-registry title ("... from the box")
                 CLEAR     the gate's audit-CLEAR title ("Merge #N (squash): audit CLEAR ...")
                 OUTSIDE   any other title: merged by hand or by a tool outside the gate
    verified   the first successful ci.yml run on LIVE whose head contains the merge commit
    sealed     the first CI "seal release <sha>" commit on LIVE whose sealed sha contains it
    adopted    the first box release identity (desks/mt5/data/release_identity.json, as published
               in LIVE's box-state commits) whose running_sha contains it AND reads ok: the box
               runs that code under a valid seal

"Contains" is git ancestry, asked of GitHub's compare API (status ahead or identical), cached per
pair. Each PR gets its lag per stage, its current stage, and what holds it.

A PR counts as touched when a human touch landed ON it, or an APPROVE MERGES landed on #453,
while it was open.

A HUMAN TOUCH, for the unattended clock, is a signal that needed zuck himself:
    * a comment by the repository owner that does NOT carry the Claude Code footer (every comment
      an agent posts carries "Generated by [Claude Code]"; a bare one was typed by a person),
      anywhere in the repo -- APPROVE MERGES, ACTIVATE, DEACTIVATE, or anything else
    * a row in desks/mt5/data/HUMAN_TOUCHES.jsonl ({"at": ..., "what": ..., "by": "zuck"}), the
      place where a thread or the box records an action only zuck could take (an RDP login, a
      settings fix, an in-chat approval); agents append, nothing here writes it
An OUTSIDE merge is not counted as a touch (an agent or a person may have made it; the account is
the same) but it is never an automatic deployment either.

AUTOMATIC DEPLOYMENT: merged through the gate (AUTO / REGISTRY / CLEAR), no human touch on that PR
between its opening and its merge, and ADOPTED.

ITEM 10 VERDICT (`autonomy_proof`):
    PROVEN     the last two adopted deployments were both automatic, no human touch for 24 h, at
               least one adoption inside those 24 h, and the box's latest identity reads ok
    NOT_YET    otherwise, with `missing` naming each unmet condition
    UNMEASURED the inputs could not be read (never resolved to a pass)

ALARMS (`red`): ADOPTION_BLOCKED (the box's identity reads not-ok), ADOPTION_LAG (a merged code PR
not adopted after 6 h), SEAL_LAG (verified but not sealed after 2 h), VERIFY_LAG (merged but no
green LIVE run after 2 h), IDENTITY_STALE (no identity published for 3 h).

Read-only on GitHub and on disk except its own two files. It never merges, seals, adopts,
re-runs, comments or cancels.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import re
import subprocess
import sys
from collections.abc import Callable, Iterable, Mapping, Sequence
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
LIVE = "claude/llm-auto-upgrade-verify-gcjac3"
REPORTS = ROOT / "desks" / "mt5" / "reports"
REPORT = REPORTS / "RELEASE_PIPELINE_PROOF.json"
HISTORY = REPORTS / "RELEASE_PIPELINE_PROOF_HISTORY.jsonl"
TOUCHES = ROOT / "desks" / "mt5" / "data" / "HUMAN_TOUCHES.jsonl"
IDENTITY_PATH = "desks/mt5/data/release_identity.json"
OWNER = "kingdemond434-cpu"
#: Where zuck types APPROVE MERGES (audit_gate reads it there).
APPROVALS_ISSUE = 453
LOOKBACK_D = 7.0
ADOPT_RED_H = 6.0
SEAL_RED_H = 2.0
VERIFY_RED_H = 2.0
IDENTITY_STALE_H = 3.0
UNATTENDED_H = 24.0
#: The Claude Code footer every agent comment carries (project rule): its absence marks a person.
AGENT_FOOTER_RE = re.compile(r"Generated by \[?Claude Code", re.I)
SEAL_RE = re.compile(r"^seal release ([0-9a-f]{7,40})\b", re.I)
GATE_TITLES = (
    ("REGISTRY", re.compile(r"^Merge #\d+ \(.*from the box\)", re.I)),
    ("AUTO", re.compile(r"^Merge #\d+ \((AUTO|LOW) tier, no comment", re.I)),
    ("CLEAR", re.compile(r"^Merge #\d+ \(\w+\): audit CLEAR [0-9a-f]{7,}", re.I)),
)
NOT_CODE_RE = re.compile(r"^(mt5 box state|seal release)\b", re.I)


def _ts(s: Any) -> datetime | None:
    if not s:
        return None
    try:
        t = datetime.fromisoformat(str(s).replace("Z", "+00:00"))
    except ValueError:
        return None
    return t if t.tzinfo else t.replace(tzinfo=UTC)


def _h(a: datetime | None, b: datetime | None) -> float | None:
    return None if a is None or b is None else round((b - a).total_seconds() / 3600.0, 2)


def merge_kind(message: str) -> str:
    first = (message or "").splitlines()[0] if message else ""
    for kind, rx in GATE_TITLES:
        if rx.search(first):
            return kind
    return "OUTSIDE"


def human_touches(
    comments: Iterable[Mapping[str, Any]], rows: Iterable[Mapping[str, Any]], owner: str = OWNER
) -> list[dict[str, Any]]:
    """Every signal that needed the person: owner comments without the agent footer, plus the
    recorded rows. Sorted by time."""
    out: list[dict[str, Any]] = []
    for c in comments:
        login = str((c.get("user") or {}).get("login") or "")
        if login.lower() != owner.lower():
            continue
        body = str(c.get("body") or "")
        if AGENT_FOOTER_RE.search(body):
            continue
        at = _ts(c.get("created_at"))
        if at is None:
            continue
        m = re.search(r"/issues/(\d+)", str(c.get("issue_url") or ""))
        out.append(
            {
                "at": at.isoformat(),
                "what": "owner comment: " + body.strip().splitlines()[0][:80]
                if body.strip()
                else "",
                "issue": int(m.group(1)) if m else None,
                "source": "github_comment",
            }
        )
    for r in rows:
        at = _ts(r.get("at"))
        if at is None:
            continue
        out.append(
            {
                "at": at.isoformat(),
                "what": str(r.get("what") or "")[:120],
                "issue": r.get("issue"),
                "source": "HUMAN_TOUCHES.jsonl",
            }
        )
    return sorted(out, key=lambda x: x["at"])


def assess(
    now: datetime,
    merged_prs: Sequence[Mapping[str, Any]],
    live_commits: Sequence[Mapping[str, Any]],
    ci_runs: Sequence[Mapping[str, Any]],
    identities: Sequence[Mapping[str, Any]],
    touches: Sequence[Mapping[str, Any]],
    contains: Callable[[str, str], bool | None],
    lookback_d: float = LOOKBACK_D,
) -> dict[str, Any]:
    """The report from already-fetched data (pure but for `contains`, the ancestry oracle, which
    the tests fake). `identities`: [{"commit_at", "running_sha", "ok", ...}] oldest first.
    `contains(anc, desc)` -> True/False, or None when it could not be asked."""
    since = now - timedelta(days=lookback_d)
    msg_by_sha = {
        str(c.get("sha")): str((c.get("commit") or {}).get("message") or "") for c in live_commits
    }
    seals = []
    for c in live_commits:
        m = SEAL_RE.match(str((c.get("commit") or {}).get("message") or ""))
        at = _ts(((c.get("commit") or {}).get("committer") or {}).get("date"))
        if m and at:
            seals.append({"at": at, "sealed": m.group(1).lower(), "commit": str(c.get("sha"))})
    seals.sort(key=lambda s: s["at"])
    green = sorted(
        (
            {"at": _ts(r.get("updated_at")), "head": str(r.get("head_sha")), "id": r.get("id")}
            for r in ci_runs
            if r.get("conclusion") == "success"
            and _ts(r.get("updated_at"))
            # LIVE's own code runs: a push or the gate's dispatch, never a PR's merge ref
            and r.get("event", "push") in ("push", "workflow_dispatch")
        ),
        key=lambda r: r["at"],  # type: ignore[arg-type,return-value]
    )
    idents = sorted(
        ({**i, "_at": _ts(i.get("commit_at"))} for i in identities if _ts(i.get("commit_at"))),
        key=lambda i: i["_at"],
    )
    touch_at = sorted(t for t in (_ts(x.get("at")) for x in touches) if t)
    unknown = 0

    def first(
        events: list[dict[str, Any]], key: str, sha: str, after: datetime
    ) -> dict[str, Any] | None:
        nonlocal unknown
        for e in events:
            at = e["at"] if "at" in e else e["_at"]
            if at is None or at < after:
                continue
            target = str(e.get(key) or "")
            if not target:
                continue
            got = contains(sha, target)
            if got is None:
                unknown += 1
                continue
            if got:
                return e
        return None

    rows: list[dict[str, Any]] = []
    for p in merged_prs:
        merged_at = _ts(p.get("merged_at"))
        sha = str(p.get("merge_commit_sha") or "")
        if merged_at is None or merged_at < since or not sha:
            continue
        kind = merge_kind(msg_by_sha.get(sha, "")) if sha in msg_by_sha else "UNREAD"
        created = _ts(p.get("created_at")) or merged_at
        num = int(p.get("number") or 0)
        # a touch FOR this PR: on the PR itself, or an APPROVE MERGES on the approvals issue,
        # while the PR was open (a person's comment elsewhere did not move this PR)
        touched = [
            x["at"]
            for x in touches
            if (_ts(x.get("at")) or now) >= created
            and (_ts(x.get("at")) or now) <= merged_at
            and (
                x.get("issue") == num
                or (x.get("issue") == APPROVALS_ISSUE and "APPROVE MERGES" in str(x.get("what")))
            )
        ]
        v = first(green, "head", sha, merged_at)
        s = first(seals, "sealed", sha, merged_at)
        a = None
        for i in idents:
            if i["_at"] < merged_at or not i.get("ok") or not i.get("running_sha"):
                continue
            got = contains(sha, str(i["running_sha"]))
            if got is None:
                unknown += 1
                continue
            if got:
                a = i
                break
        v_at = v["at"] if v else None
        s_at = s["at"] if s else None
        a_at = a["_at"] if a else None
        stage = "ADOPTED" if a else "SEALED" if s else "VERIFIED" if v else "MERGED"
        holds = None
        if not a:
            holds = (
                "no green ci.yml run on LIVE contains the merge yet"
                if not v
                else "verified; no CI seal contains it yet"
                if not s
                else "sealed; the box has not published an ok identity running it"
            )
        automatic = kind in ("AUTO", "REGISTRY", "CLEAR") and not touched
        rows.append(
            {
                "pr": num,
                "title": str(p.get("title") or "")[:100],
                "merge_commit": sha[:12],
                "merged_at": merged_at.isoformat(),
                "merged_by_gate": kind,
                "human_touches_before_merge": touched,
                "automatic": automatic,
                "stage": stage,
                "holds": holds,
                "verified_at": v_at.isoformat() if v_at else None,
                "verify_run": v.get("id") if v else None,
                "sealed_at": s_at.isoformat() if s_at else None,
                "seal": s["sealed"][:12] if s else None,
                "adopted_at": a_at.isoformat() if a_at else None,
                "lag_h": {
                    "merge_to_verified": _h(merged_at, v_at),
                    "verified_to_sealed": _h(v_at, s_at),
                    "sealed_to_adopted": _h(s_at, a_at),
                    "merge_to_adopted": _h(merged_at, a_at),
                },
                "age_h": _h(merged_at, now),
            }
        )
    rows.sort(key=lambda r: r["merged_at"])

    # ---- health of the adoption end -------------------------------------------------------
    latest = idents[-1] if idents else None
    red: list[str] = []
    if latest is None:
        red.append("IDENTITY_UNREAD: no box release identity in the lookback")
    else:
        if not latest.get("ok"):
            red.append(f"ADOPTION_BLOCKED: box identity not ok: {str(latest.get('reason'))[:160]}")
        age = _h(latest["_at"], now)
        if age is not None and age > IDENTITY_STALE_H:
            red.append(f"IDENTITY_STALE: last identity published {age:.1f} h ago")
    code_rows = [r for r in rows if r["stage"] != "ADOPTED"]
    for r in code_rows:
        age = r["age_h"] or 0.0
        if r["stage"] == "MERGED" and age > VERIFY_RED_H:
            red.append(f"VERIFY_LAG: #{r['pr']} merged {age:.1f} h ago, no green LIVE run")
        elif r["stage"] == "VERIFIED" and (_h(_ts(r["verified_at"]), now) or 0) > SEAL_RED_H:
            red.append(f"SEAL_LAG: #{r['pr']} verified, not sealed")
        if age > ADOPT_RED_H:
            red.append(
                f"ADOPTION_LAG: #{r['pr']} not adopted {age:.1f} h after merge ({r['stage']})"
            )

    adopted = [r for r in rows if r["stage"] == "ADOPTED"]
    lags = sorted(x for x in (r["lag_h"]["merge_to_adopted"] for r in adopted) if x is not None)

    def pct(q: float) -> float | None:
        if not lags:
            return None
        return float(lags[min(len(lags) - 1, round(q * (len(lags) - 1)))])

    # ---- item 10: two consecutive automatic deployments + 24 h unattended -----------------
    by_adopt = sorted(adopted, key=lambda r: r["adopted_at"])
    streak = 0
    for r in reversed(by_adopt):
        if not r["automatic"]:
            break
        streak += 1
    last_touch = touch_at[-1] if touch_at else None
    unattended_h = _h(last_touch, now) if last_touch else round(lookback_d * 24.0, 2)
    window_start = now - timedelta(hours=UNATTENDED_H)
    adopted_in_window = [r for r in by_adopt if (_ts(r["adopted_at"]) or now) >= window_start]
    missing: list[str] = []
    if streak < 2:
        missing.append(f"consecutive automatic adopted deployments {streak} < 2")
    if unattended_h is not None and unattended_h < UNATTENDED_H:
        missing.append(f"last human touch {unattended_h:.1f} h ago < 24 h")
    if not adopted_in_window:
        missing.append("no adoption inside the last 24 h")
    if latest is None or not latest.get("ok"):
        missing.append("the box's latest release identity is not ok")
    verdict = "UNMEASURED" if latest is None else "PROVEN" if not missing else "NOT_YET"

    return {
        "at": now.isoformat(timespec="seconds"),
        "status": "RED" if red else "GREEN",
        "red": red,
        "lookback_d": lookback_d,
        "box": None
        if latest is None
        else {
            "running_sha": str(latest.get("running_sha") or "")[:12],
            "ok": bool(latest.get("ok")),
            "allows_new_risk": latest.get("allows_new_risk"),
            "reason": str(latest.get("reason") or "")[:240],
            "published_at": latest["_at"].isoformat(),
        },
        "speed": {
            "merged": len(rows),
            "adopted": len(adopted),
            "not_adopted": len(rows) - len(adopted),
            "merge_to_adopted_h_p50": pct(0.5),
            "merge_to_adopted_h_p90": pct(0.9),
            "oldest_unadopted_h": max((r["age_h"] or 0.0 for r in code_rows), default=None),
            "by_stage": {
                s: sum(r["stage"] == s for r in rows)
                for s in ("MERGED", "VERIFIED", "SEALED", "ADOPTED")
            },
            "by_merge_kind": {
                k: sum(r["merged_by_gate"] == k for r in rows)
                for k in ("AUTO", "REGISTRY", "CLEAR", "OUTSIDE", "UNREAD")
            },
        },
        "autonomy_proof": {
            "verdict": verdict,
            "missing": missing,
            "consecutive_automatic_deployments": streak,
            "hours_since_human_touch": unattended_h,
            "last_human_touch": None if last_touch is None else last_touch.isoformat(),
            "adoptions_last_24h": len(adopted_in_window),
            "human_touches_in_lookback": len(touch_at),
        },
        "ancestry_unanswered": unknown,
        "human_touches": list(touches)[-20:],
        "prs": rows,
        "thresholds": {
            "adopt_red_h": ADOPT_RED_H,
            "seal_red_h": SEAL_RED_H,
            "verify_red_h": VERIFY_RED_H,
            "identity_stale_h": IDENTITY_STALE_H,
            "unattended_h": UNATTENDED_H,
        },
    }


# ---- fetching (gh api, read-only) ------------------------------------------------------------


def _gh(path: str) -> Any:
    gh = os.environ.get("GH_BIN") or "gh"
    p = subprocess.run(
        [gh, "api", path],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
        timeout=60,
    )
    if p.returncode != 0:
        raise RuntimeError(f"gh api {path}: {p.stderr.strip()[:300]}")
    return json.loads(p.stdout or "null")


def _pages(path: str, pages: int, key: str | None = None) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    sep = "&" if "?" in path else "?"
    for page in range(1, pages + 1):
        got = _gh(f"{path}{sep}per_page=100&page={page}")
        batch = (got.get(key) if key else got) or []
        out += batch
        if len(batch) < 100:
            break
    return out


def _read_rows(path: Path) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    try:
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            try:
                d = json.loads(line)
            except ValueError:
                continue
            if isinstance(d, dict):
                out.append(d)
    except OSError:
        pass
    return out


def collect(
    repo: str,
    base: str = LIVE,
    lookback_d: float = LOOKBACK_D,
    max_identities: int = 80,
    touches_path: Path = TOUCHES,
) -> dict[str, Any]:
    now = datetime.now(UTC)
    since = (now - timedelta(days=lookback_d)).strftime("%Y-%m-%dT%H:%M:%SZ")
    closed = _pages(f"repos/{repo}/pulls?state=closed&base={base}&sort=updated&direction=desc", 3)
    merged = [p for p in closed if p.get("merged_at")]
    live = _pages(f"repos/{repo}/commits?sha={base}&since={since}", 10)
    runs = _pages(
        f"repos/{repo}/actions/workflows/ci.yml/runs?branch={base}&status=success&created={'>='}{since[:10]}",
        3,
        key="workflow_runs",
    )
    id_commits = _pages(f"repos/{repo}/commits?sha={base}&path={IDENTITY_PATH}&since={since}", 3)
    identities: list[dict[str, Any]] = []
    for c in id_commits[:max_identities]:
        try:
            doc = _gh(f"repos/{repo}/contents/{IDENTITY_PATH}?ref={c['sha']}")
            ident = json.loads(base64.b64decode(doc.get("content") or "").decode("utf-8"))
        except (RuntimeError, ValueError, KeyError):
            continue
        if isinstance(ident, dict):
            identities.append(
                {
                    "commit_at": ((c.get("commit") or {}).get("committer") or {}).get("date"),
                    "running_sha": ident.get("running_sha"),
                    "ok": ident.get("ok"),
                    "allows_new_risk": ident.get("allows_new_risk"),
                    "reason": ident.get("reason"),
                }
            )
    comments = _pages(f"repos/{repo}/issues/comments?since={since}&sort=created", 10)
    touches = human_touches(comments, _read_rows(touches_path))
    cache: dict[tuple[str, str], bool | None] = {}

    def contains(anc: str, desc: str) -> bool | None:
        if not anc or not desc:
            return None
        if desc.startswith(anc) or anc.startswith(desc):
            return True
        k = (anc, desc)
        if k not in cache:
            try:
                st = _gh(f"repos/{repo}/compare/{anc}...{desc}").get("status")
                cache[k] = st in ("ahead", "identical")
            except (RuntimeError, subprocess.TimeoutExpired) as exc:
                # a commit GitHub no longer has (a run's merge ref, a rewritten head) contains
                # nothing; any other failure is unanswered, never a "no"
                cache[k] = False if "HTTP 404" in str(exc) or "HTTP 422" in str(exc) else None
                errors.append(str(exc)[:200])
        return cache[k]

    errors: list[str] = []
    rep = assess(now, merged, live, runs, identities, touches, contains, lookback_d)
    rep["ancestry_errors"] = errors[:5]
    return rep


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--repo", required=True)
    ap.add_argument("--base", default=LIVE)
    ap.add_argument("--out", type=Path, default=REPORT)
    ap.add_argument("--history", type=Path, default=HISTORY)
    ap.add_argument("--lookback-d", type=float, default=LOOKBACK_D)
    ap.add_argument("--touches", type=Path, default=TOUCHES, help="the box's HUMAN_TOUCHES.jsonl")
    ap.add_argument("--print", action="store_true", help="stdout only, write nothing")
    ap.add_argument(
        "--min-interval-min",
        type=float,
        default=55.0,
        help="skip when --out is younger (hourly is enough for lags in hours)",
    )
    a = ap.parse_args(argv)
    if not a.print and a.min_interval_min > 0:
        try:
            prev = json.loads(a.out.read_text(encoding="utf-8"))
            t = _ts(prev.get("at"))
            if t and (datetime.now(UTC) - t).total_seconds() / 60.0 < a.min_interval_min:
                print("release proof fresh: not re-read")
                return 0
        except (OSError, ValueError):
            pass
    try:
        rep = collect(a.repo, a.base, a.lookback_d, touches_path=a.touches)
    except (RuntimeError, ValueError, subprocess.TimeoutExpired) as exc:
        rep = {
            "at": datetime.now(UTC).isoformat(timespec="seconds"),
            "status": "RED",
            "red": [f"PROOF_BLIND: {exc}"],
            "autonomy_proof": {"verdict": "UNMEASURED", "missing": ["inputs unreadable"]},
        }
    text = json.dumps(rep, indent=1)
    if a.print:
        print(text)
        return 0
    a.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = a.out.with_suffix(".tmp")
    tmp.write_text(text + "\n", encoding="utf-8")
    tmp.replace(a.out)
    line = {
        "at": rep["at"],
        "status": rep["status"],
        "red": len(rep.get("red") or []),
        "speed": rep.get("speed"),
        "autonomy_proof": rep.get("autonomy_proof"),
    }
    with a.history.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(line) + "\n")
