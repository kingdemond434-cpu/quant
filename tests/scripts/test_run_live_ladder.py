# ------------------------------------------------------------------- honest refusal


def test_WITH_NOTHING_TO_LADDER_IT_BLOCKS_RATHER_THAN_REPORTING_AN_EMPTY_LADDER(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """No records and no survivors is UNMEASURED, not a ladder with nothing on it -- and the two
    read completely differently to whoever opens the artifact next."""
    out = tmp_path / "rep.json"
    monkeypatch.setattr(sys, "argv", ["run_live_ladder.py", "--records", str(tmp_path / "a.json"),
                                      "--sweep", str(tmp_path / "b.json"), "--out", str(out)])
    assert RL.main() == 0
    rep = json.loads(out.read_text())
    assert rep["verdict"].startswith("BLOCKED")
    assert "UNMEASURED, not an empty ladder" in rep["reason"]
    assert "Gate-0" in rep["reason"] and "GAP #91" in rep["reason"]


def test_A_MALFORMED_RECORD_IS_SKIPPED_NEVER_DEFAULTED_INTO_EXISTENCE() -> None:
    """A row missing its trade count defaulted to zero would become an UNDERPOWERED verdict about a
    strategy that has no record at all -- a verdict invented from a parse failure."""
    rows = RL.records_from({"records": [
        {"name": "ok", "n_trades": 10, "mean_bps": 1.0, "sd_bps": 2.0},
        {"name": "no_trades", "mean_bps": 1.0, "sd_bps": 2.0},
        {"name": "junk", "n_trades": "many", "mean_bps": 1.0, "sd_bps": 2.0},
    ]})
    assert [r.name for r in rows] == ["ok"]


def test_AN_ABSENT_SWEEP_YIELDS_NO_SURVIVORS_RATHER_THAN_RAISING() -> None:
    assert RL.survivors_from(None) == []
    assert RL.survivors_from({"survivors": []}) == []


def test_THE_SCRIPT_PLACES_NOTHING_AND_SAYS_SO(tmp_path: Path,
                                               monkeypatch: pytest.MonkeyPatch) -> None:
    """Arming live trading is the principal's act; the dead-man rail is never touched."""
    out = tmp_path / "rep.json"
    monkeypatch.setattr(sys, "argv", ["run_live_ladder.py", "--records", str(tmp_path / "a.json"),
                                      "--sweep", str(tmp_path / "b.json"), "--out", str(out)])
    RL.main()
    assert "places no orders" in json.loads(out.read_text())["authority"]
    src = Path("scripts/run_live_ladder.py").read_text("utf-8")
    for token in ("place_market", "place_order", "binance", "api_key"):
        assert token not in src.lower(), f"the bridge reached toward an order path: {token!r}"
