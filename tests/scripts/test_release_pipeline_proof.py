"""Release pipeline proof: merged -> verified -> sealed -> adopted, and directive item 10."""

from __future__ import annotations

import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import release_pipeline_proof as rpp  # noqa: E402

NOW = datetime(2026, 11, 20, 12, 0, tzinfo=UTC)
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def iso(h_ago: float) -> str:
    return (NOW - timedelta(hours=h_ago)).isoformat()


#: A linear LIVE history: each sha contains every sha with a smaller index.
ORDER = ["a1a1a1a", "b1b1b1b", "c1c1c1c", "a2a2a2a", "b2b2b2b", "c2c2c2c", "d2d2d2d", "a3a3a3a"]


def contains(anc: str, desc: str) -> bool | None:
    if anc not in ORDER or desc not in ORDER:
        return None
    return ORDER.index(anc) <= ORDER.index(desc)


def pr(n: int, sha: str, merged_h: float, opened_h: float = 40.0) -> dict[str, Any]:
    return {
        "number": n,
        "title": f"pr {n}",
        "merge_commit_sha": sha,
        "merged_at": iso(merged_h),
        "created_at": iso(opened_h),
    }


def commit(sha: str, msg: str, h: float) -> dict[str, Any]:
    return {"sha": sha, "commit": {"message": msg, "committer": {"date": iso(h)}}}


def world(
    kind1: str = "Merge #1 (AUTO tier, no comment: code)",
    kind2: str = "Merge #2 (squash): audit CLEAR abcdef123",
    ident_ok: bool = True,
) -> dict[str, Any]:
    return {
        "merged_prs": [pr(1, "a1a1a1a", 30.0), pr(2, "a2a2a2a", 20.0)],
        "live_commits": [
            commit("a1a1a1a", kind1, 30.0),
            commit("e1e1e1e", "seal release c1c1c1c", 28.0),
            commit("a2a2a2a", kind2, 20.0),
            commit("e2e2e2e", "seal release c2c2c2c", 18.0),
        ],
        "ci_runs": [
            {"id": 11, "head_sha": "b1b1b1b", "conclusion": "success", "updated_at": iso(29.0)},
            {"id": 12, "head_sha": "b2b2b2b", "conclusion": "success", "updated_at": iso(19.0)},
        ],
        "identities": [
            {"commit_at": iso(27.0), "running_sha": "c1c1c1c", "ok": True},
            {"commit_at": iso(17.0), "running_sha": "d2d2d2d", "ok": True},
            {"commit_at": iso(0.5), "running_sha": "d2d2d2d", "ok": ident_ok, "reason": "x"},
        ],
    }


def run(touches: list[dict[str, Any]] | None = None, **kw: Any) -> dict[str, Any]:
    w = world(**kw)
    return rpp.assess(
        NOW,
        w["merged_prs"],
        w["live_commits"],
        w["ci_runs"],
        w["identities"],
        touches or [],
        contains,
    )


def test_two_automatic_adoptions_and_a_quiet_day_prove_item_10() -> None:
    rep = run()
    rows = {r["pr"]: r for r in rep["prs"]}
    assert rows[1]["stage"] == rows[2]["stage"] == "ADOPTED"
    assert rows[1]["merged_by_gate"] == "AUTO" and rows[2]["merged_by_gate"] == "CLEAR"
    assert rows[1]["lag_h"] == {
        "merge_to_verified": 1.0,
        "verified_to_sealed": 1.0,
        "sealed_to_adopted": 1.0,
        "merge_to_adopted": 3.0,
    }
    proof = rep["autonomy_proof"]
    assert proof["verdict"] == "PROVEN", proof["missing"]
    assert proof["consecutive_automatic_deployments"] == 2
    assert rep["status"] == "GREEN" and rep["speed"]["merge_to_adopted_h_p50"] == 3.0


def test_an_approve_merges_while_the_pr_was_open_makes_it_not_automatic() -> None:
    touches = rpp.human_touches(
        [
            {
                "user": {"login": rpp.OWNER},
                "body": "APPROVE MERGES",
                "created_at": iso(22.0),
                "issue_url": f"https://api.github.com/repos/o/r/issues/{rpp.APPROVALS_ISSUE}",
            }
        ],
        [],
    )
    rep = run(touches)
    rows = {r["pr"]: r for r in rep["prs"]}
    assert rows[1]["automatic"] is True  # merged before the touch
    assert rows[2]["automatic"] is False and rows[2]["human_touches_before_merge"]
    proof = rep["autonomy_proof"]
    assert proof["verdict"] == "NOT_YET"
    assert proof["consecutive_automatic_deployments"] == 0
    assert any("< 24 h" in m for m in proof["missing"])


def test_agent_comments_and_other_users_are_not_human_touches() -> None:
    got = rpp.human_touches(
        [
            {
                "user": {"login": rpp.OWNER},
                "body": "AUDIT CLEAR abc" + FOOTER,
                "created_at": iso(1),
                "issue_url": ".../issues/5",
            },
            {"user": {"login": "someone"}, "body": "hi", "created_at": iso(1)},
            {
                "user": {"login": rpp.OWNER},
                "body": "ACTIVATE LIVE AUTO-MERGE",
                "created_at": iso(2),
                "issue_url": ".../issues/453",
            },
        ],
        [{"at": iso(3), "what": "RDP login to fix settings.json", "by": "zuck"}],
    )
    assert [t["source"] for t in got] == ["HUMAN_TOUCHES.jsonl", "github_comment"]
    assert got[1]["issue"] == 453


def test_a_blocked_box_is_red_and_never_proven() -> None:
    rep = run(ident_ok=False)
    assert rep["status"] == "RED"
    assert any(r.startswith("ADOPTION_BLOCKED") for r in rep["red"])
    assert rep["autonomy_proof"]["verdict"] == "NOT_YET"
    assert "the box's latest release identity is not ok" in rep["autonomy_proof"]["missing"]


def test_a_merge_with_no_green_live_run_is_held_at_merged_with_its_lags() -> None:
    w = world()
    w["merged_prs"].append(pr(3, "a3a3a3a", 7.0))
    w["live_commits"].append(commit("a3a3a3a", "Merge pull request #3 from x/y", 7.0))
    rep = rpp.assess(
        NOW, w["merged_prs"], w["live_commits"], w["ci_runs"], w["identities"], [], contains
    )
    row = {r["pr"]: r for r in rep["prs"]}[3]
    assert row["stage"] == "MERGED" and row["merged_by_gate"] == "OUTSIDE"
    assert row["automatic"] is False and "no green ci.yml run" in row["holds"]
    assert any(r.startswith("VERIFY_LAG: #3") for r in rep["red"])
    assert any(r.startswith("ADOPTION_LAG: #3") for r in rep["red"])


def test_an_unanswered_ancestry_never_counts_as_adopted() -> None:
    w = world()
    rep = rpp.assess(
        NOW,
        w["merged_prs"],
        w["live_commits"],
        w["ci_runs"],
        w["identities"],
        [],
        lambda a, d: None,
    )
    assert all(r["stage"] == "MERGED" for r in rep["prs"])
    assert rep["ancestry_unanswered"] > 0
    assert rep["autonomy_proof"]["verdict"] == "NOT_YET"


def test_no_identity_is_unmeasured_not_a_pass() -> None:
    w = world()
    rep = rpp.assess(NOW, w["merged_prs"], w["live_commits"], w["ci_runs"], [], [], contains)
    assert rep["autonomy_proof"]["verdict"] == "UNMEASURED"
    assert any(r.startswith("IDENTITY_UNREAD") for r in rep["red"])


def test_pr_merge_ref_runs_never_verify_live() -> None:
    w = world()
    for r in w["ci_runs"]:
        r["event"] = "pull_request"
    rep = rpp.assess(
        NOW, w["merged_prs"], w["live_commits"], w["ci_runs"], w["identities"], [], contains
    )
    assert all(r["verified_at"] is None for r in rep["prs"])


