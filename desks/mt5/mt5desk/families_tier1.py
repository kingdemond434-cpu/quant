"""TIER-1 IDEA FAMILIES: four mechanisms from the 2026-11-11 "closing the gap to tier 1" list
that no registered family could express on desk bars.

The build check of 2026-11-18 listed these ideas as partial or wired-but-not-producing. The
research side (`research/specialist_cell.py`) names the cells; these are the signal functions
the sealed gauntlet builds them with. Each loads any foreign series itself from the bar store,
given only what the cell carries, as `families_specialist` does, so `build_cell` needs no input
branch. Desk bars only: nothing here reads an external feed.

  overnight_intraday_tug   U2. Lou, Polk & Skouras (2019), "A tug of war: overnight versus
      intraday expected returns": the overnight leg (prior cash close -> cash open) and the day
      leg (cash open -> cash close) are earned by different clienteles. When today's night leg
      DISAGREES in sign with yesterday's day leg, the day session tends to reverse the night
      leg. `direction=-1` fades the night leg (the claim), `+1` is the mirror the gauntlet also
      judges. Venue clocks are local (`mt5desk/local_clock.py`), DST-exact.
  weekend_driver_gap       U4. Fusion's crypto CFDs trade Saturday and Sunday while FX, gold
      and index CFDs are shut. The driver's move between the target's last pre-weekend bar and
      its first bar back is information the target has not traded on; the Monday gap may
      under-react. Fires only on a target bar that follows a closure of at least `min_gap_h`
      hours, sized by the weekend move's z against PRIOR weekends only.
  equity_gap_breadth       U5. Earnings season moves single names at the open by several percent;
      the share of the share-CFD class that gapped up minus the share that gapped down by at
      least `gap_min` is a breadth of news the index has absorbed only partly. Read after the
      cash session, traded on the index into the next day.
  pre_holiday_drift        N1. Ariel (1990), Lakonishok & Smidt (1988): index returns on the
      session before an exchange holiday are abnormally positive. Holidays are generated by rule
      per venue (NYSE, Xetra, LSE) from the date alone, never from whether the bars stopped.

NO LOOKAHEAD. A decision at bar i uses bar i's close (the engine enters at the next open,
`wait_bars=1`); a foreign series is read as of bar i's stamp, i.e. bars that closed by the
decision. Weekend z-scores use earlier weekends only.

HONEST LIMITS. A malformed clock, an unknown venue or a missing driver returns [] (never a
price-only fallback). Holiday rules cover the regular calendars; one-off closures (a state
funeral, a hurricane day) are not in them and the family does not see them. JPX's calendar is
not generated here: `venue="JPX"` returns [], which is said rather than guessed.
"""
from __future__ import annotations

from collections.abc import Callable
from datetime import date, timedelta
from typing import Any

import numpy as np
import pandas as pd
from mt5desk import local_clock as _LC
from mt5desk.families import Signal, _atr

_NS_PER_H = 3_600_000_000_000


def _sig(d: pd.DataFrame, i: int, side: int, atr: np.ndarray, *, stop_atr: float, rr: float,
         hold_bars: int, tag: str) -> Signal | None:
    a = float(atr[i])
    px = float(d["close"].iloc[i])
    if not np.isfinite(a) or a <= 0 or not np.isfinite(px) or side == 0:
        return None
    return Signal(time=d.index[i], side=int(side), stop=px - side * stop_atr * a,
                  target=px + side * stop_atr * a * rr, ttl_bars=int(hold_bars), tag=tag,
                  trigger=None, wait_bars=1)


def _first_per_date(mask: np.ndarray, ymd: np.ndarray) -> dict[int, int]:
    out: dict[int, int] = {}
    for i in np.flatnonzero(mask):
        out.setdefault(int(ymd[i]), int(i))
    return out


# ------------------------------------------------------------------------------- U2 tug ---
def family_overnight_intraday_tug(
    df: pd.DataFrame,
    *,
    venue_tz: str = "America/New_York",
    open_at: str = "09:30",
    close_at: str = "16:00",
    min_leg_atr: float = 0.3,
    direction: int = -1,
    hold_bars: int = 6,
    atr_n: int = 20,
    stop_atr: float = 1.5,
    rr: float = 1.5,
) -> list[Signal]:
    """At the bar containing the cash open: night leg N = open-bar open / prior close-bar close,
    yesterday's day leg D = close-bar close / open-bar open (prior local date). Fire when both
    legs clear `min_leg_atr` ATR and disagree in sign; side = direction * sign(N)."""
    if df.empty or direction not in (-1, 1):
        return []
    om = _LC.window_mask(df.index, venue_tz, open_at, "contains")
    cm = _LC.window_mask(df.index, venue_tz, close_at, "contains")
    if om is None or cm is None:
        return []
    _m, ymd = _LC.local_frame(df.index, venue_tz)
    opens = _first_per_date(om, ymd)
    closes = _first_per_date(cm, ymd)
    o = df["open"].to_numpy(dtype=float)
    c = df["close"].to_numpy(dtype=float)
    atr = _atr(df, atr_n).to_numpy(dtype=float)
    dates = sorted(opens)
    out: list[Signal] = []
    for k in range(1, len(dates)):
        today, prev = dates[k], dates[k - 1]
        i = opens[today]
        pj, po = closes.get(prev), opens.get(prev)
        if pj is None or po is None or not po < pj < i or i >= len(df) - 1:
            continue
        a = atr[i]
        if not np.isfinite(a) or a <= 0:
            continue
        night = o[i] - c[pj]
        day = c[pj] - o[po]
        if min(abs(night), abs(day)) < min_leg_atr * a or np.sign(night) == np.sign(day):
            continue
        s = _sig(df, i, direction * int(np.sign(night)), atr, stop_atr=stop_atr, rr=rr,
                 hold_bars=hold_bars, tag="overnight_intraday_tug")
        if s is not None:
            out.append(s)
    return out


# ----------------------------------------------------------------------- U4 weekend gap ---
def _driver_asof(stamps_ns: np.ndarray, symbol: str) -> np.ndarray:
    from mt5desk.families_specialist import asof_close
    # a bar's close is known at stamp + 1h; reading the driver as of the target stamp + 1h
    # (the decision time) admits only driver bars stamped at or before the target bar
    return asof_close(stamps_ns, symbol, max_stale_h=6.0)


def family_weekend_driver_gap(
    df: pd.DataFrame,
    *,
    driver_symbol: str = "BTCUSD",
    min_gap_h: float = 36.0,
    entry_z: float = 1.0,
    min_history: int = 26,
    direction: int = 1,
    hold_bars: int = 6,
    atr_n: int = 20,
    stop_atr: float = 1.5,
    rr: float = 1.5,
) -> list[Signal]:
    """On the first target bar after a closure of >= `min_gap_h` hours: the driver's log move
    from the target's last pre-closure bar to this bar, z-scored against prior closures only.
    |z| >= entry_z fires side = direction * sign(move)."""
    if df.empty or not driver_symbol or direction not in (-1, 1):
        return []
    idx = pd.DatetimeIndex(df.index)
    if idx.tz is None:
        idx = idx.tz_localize("UTC")
    t = idx.as_unit("ns").asi8
    if t.size < 3:
        return []
    gaps = np.diff(t) >= int(min_gap_h * _NS_PER_H)
    first = np.flatnonzero(gaps) + 1
    if first.size == 0:
        return []
    drv = _driver_asof(t, driver_symbol)
    atr = _atr(df, atr_n).to_numpy(dtype=float)
    hist: list[float] = []
    out: list[Signal] = []
    for i in first:
        if i >= len(df) - 1:
            continue
        before, after = drv[i - 1], drv[i]
        if not (np.isfinite(before) and np.isfinite(after) and before > 0 and after > 0):
            continue
        move = float(np.log(after / before))
        if len(hist) >= min_history:
            sd = float(np.std(hist, ddof=1))
            z = move / sd if sd > 0 else 0.0
            if abs(z) >= entry_z:
                s = _sig(df, int(i), direction * int(np.sign(move)), atr, stop_atr=stop_atr,
                         rr=rr, hold_bars=hold_bars,
                         tag=f"weekend_driver_gap:{driver_symbol}")
                if s is not None:
                    out.append(s)
        hist.append(move)
    return out


# ---------------------------------------------------------------- U5 equity gap breadth ---
_GAP_CACHE: dict[tuple[str, str], Any] = {}


def _members(currency: str) -> list[str]:
    from research import universe_policy as up
    reg = up._registry()
    out = []
    for sym in up.class_members("equity"):
        row = reg.get(sym) or reg.get(str(sym).upper()) or {}
        if not currency or str(row.get("currency_profit") or "").upper() == currency.upper():
            out.append(sym)
    return out


def _daily_gaps(symbol: str, tz: str) -> pd.Series | None:
    """Per local date of `tz`: first bar's open / previous date's last close - 1."""
    from mt5desk import families_cross_sectional as xs
    path = xs.UNIVERSE_DIR / f"{symbol}_H1.parquet"
    try:
        mtime = path.stat().st_mtime_ns
    except OSError:
        return None
    key = (symbol, tz)
    hit = _GAP_CACHE.get(key)
    if hit is not None and hit[0] == mtime:
        return hit[1]
    try:
        f = pd.read_parquet(path, columns=["open", "close"])
    except Exception:
        return None
    if not isinstance(f.index, pd.DatetimeIndex) or f.empty:
        return None
    f = f[~f.index.duplicated(keep="last")].sort_index()
    _m, ymd = _LC.local_frame(f.index, tz)
    g = pd.DataFrame({"o": f["open"].to_numpy(float), "c": f["close"].to_numpy(float),
                      "d": ymd}).groupby("d")
    first_open = g["o"].first()
    last_close = g["c"].last()
    gaps = first_open / last_close.shift(1) - 1.0
    gaps = gaps.replace([np.inf, -np.inf], np.nan).dropna()
    _GAP_CACHE[key] = (mtime, gaps)
    if len(_GAP_CACHE) > 400:
        _GAP_CACHE.pop(next(iter(_GAP_CACHE)))
    return gaps


def family_equity_gap_breadth(
    df: pd.DataFrame,
    *,
    peer_currency: str = "USD",
    venue_tz: str = "America/New_York",
    decide_at: str = "16:00",
    gap_min: float = 0.03,
    min_names: int = 20,
    entry_breadth: float = 0.05,
    direction: int = 1,
    hold_bars: int = 22,
    atr_n: int = 20,
    stop_atr: float = 2.0,
    rr: float = 1.5,
) -> list[Signal]:
    """At the target bar containing `decide_at` local on each date: breadth = (names that gapped
    up by >= gap_min - names that gapped down by >= gap_min) / names with a gap that date, over
    the share-CFD class quoted in `peer_currency`. |breadth| >= entry_breadth with at least
    `min_names` reporting fires side = direction * sign(breadth), held into the next session."""
    if df.empty or direction not in (-1, 1):
        return []
    dm = _LC.window_mask(df.index, venue_tz, decide_at, "contains")
    if dm is None:
        return []
    cols = {}
    for sym in _members(peer_currency):
        s = _daily_gaps(sym, venue_tz)
        if s is not None and len(s):
            cols[sym] = s
    if not cols:
        return []
    panel = pd.DataFrame(cols)
    n = panel.notna().sum(axis=1)
    up = (panel >= gap_min).sum(axis=1)
    down = (panel <= -gap_min).sum(axis=1)
    breadth = ((up - down) / n.where(n > 0)).where(n >= min_names)
    _m, ymd = _LC.local_frame(df.index, venue_tz)
    atr = _atr(df, atr_n).to_numpy(dtype=float)
    out: list[Signal] = []
    for d, i in _first_per_date(dm, ymd).items():
        if i >= len(df) - 1:
            continue
        b = breadth.get(d)
        if b is None or not np.isfinite(b) or abs(float(b)) < entry_breadth:
            continue
        s = _sig(df, i, direction * int(np.sign(b)), atr, stop_atr=stop_atr, rr=rr,
                 hold_bars=hold_bars, tag="equity_gap_breadth")
        if s is not None:
            out.append(s)
    return out


# ------------------------------------------------------------------ N1 pre-holiday drift ---
def easter(year: int) -> date:
    """Western Easter Sunday (anonymous Gregorian algorithm)."""
    a = year % 19
    b, c = divmod(year, 100)
    d, e = divmod(b, 4)
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = divmod(c, 4)
    l_ = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l_) // 451
    month, day = divmod(h + l_ - 7 * m + 114, 31)
    return date(year, month, day + 1)


def _nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    d = date(year, month, 1)
    d += timedelta(days=(weekday - d.weekday()) % 7)
    return d + timedelta(weeks=n - 1)


def _last_weekday(year: int, month: int, weekday: int) -> date:
    d = date(year + (month == 12), month % 12 + 1, 1) - timedelta(days=1)
    return d - timedelta(days=(d.weekday() - weekday) % 7)


def _observed_us(d: date) -> date:
    return d - timedelta(days=1) if d.weekday() == 5 else (
        d + timedelta(days=1) if d.weekday() == 6 else d)


def _observed_uk(d: date) -> date:
    return d + timedelta(days=(7 - d.weekday()) % 7) if d.weekday() >= 5 else d


def holidays(venue: str, year: int) -> set[date]:
    """The venue's regular full-day closures in `year`, by rule. Empty for an unknown venue."""
    v = venue.upper()
    ef = easter(year) - timedelta(days=2)
    em = easter(year) + timedelta(days=1)
    if v == "NYSE":
        out = {_nth_weekday(year, 1, 0, 3), _nth_weekday(year, 2, 0, 3), ef,
               _last_weekday(year, 5, 0), _observed_us(date(year, 7, 4)),
               _nth_weekday(year, 9, 0, 1), _nth_weekday(year, 11, 3, 4),
               _observed_us(date(year, 12, 25))}
        ny = date(year, 1, 1)
        if ny.weekday() != 5:                         # NYSE does not observe a Saturday NYD
            out.add(_observed_us(ny))
        if year >= 2022:
            out.add(_observed_us(date(year, 6, 19)))
        return out
    if v == "XETRA":
        return {d for d in (date(year, 1, 1), ef, em, date(year, 5, 1), date(year, 12, 24),
                            date(year, 12, 25), date(year, 12, 26), date(year, 12, 31))
                if d.weekday() < 5}
    if v == "LSE":
        xmas = _observed_uk(date(year, 12, 25))
        boxing = _observed_uk(date(year, 12, 26))
        if boxing == xmas:
            boxing = xmas + timedelta(days=1)
        return {_observed_uk(date(year, 1, 1)), ef, em, _nth_weekday(year, 5, 0, 1),
                _last_weekday(year, 5, 0), _last_weekday(year, 8, 0), xmas, boxing}
    return set()


VENUES: dict[str, tuple[str, str]] = {
    # venue -> (local zone, cash close "HH:MM")
    "NYSE": ("America/New_York", "16:00"),
    "XETRA": ("Europe/Berlin", "17:30"),
    "LSE": ("Europe/London", "16:30"),
}


def pre_holiday_sessions(venue: str, years: range, days_before: int) -> set[int]:
    """YYYYMMDD of the `days_before` trading sessions immediately before each holiday."""
    out: set[int] = set()
    hol: set[date] = set()
    for y in years:
        hol |= holidays(venue, y)
    for h in sorted(hol):
        d, found = h, 0
        while found < days_before:
            d -= timedelta(days=1)
            if d.weekday() < 5 and d not in hol:
                out.add(d.year * 10000 + d.month * 100 + d.day)
                found += 1
    return out


def family_pre_holiday_drift(
    df: pd.DataFrame,
    *,
    venue: str = "NYSE",
    days_before: int = 1,
    side: int = 1,
    hold_bars: int = 23,
    atr_n: int = 20,
    stop_atr: float = 2.0,
    rr: float = 1.5,
) -> list[Signal]:
    """At the bar containing the venue's cash close on the session BEFORE the first pre-holiday
    session, take `side` and hold `hold_bars` (through the pre-holiday close)."""
    v = str(venue).upper()
    if df.empty or v not in VENUES or side not in (-1, 1) or days_before < 1:
        return []
    tz, close_at = VENUES[v]
    cm = _LC.window_mask(df.index, tz, close_at, "contains")
    if cm is None:
        return []
    _m, ymd = _LC.local_frame(df.index, tz)
    years = range(int(ymd.min()) // 10000 - 1, int(ymd.max()) // 10000 + 2)
    pre = pre_holiday_sessions(v, years, int(days_before))
    hol: set[date] = set()
    for y in years:
        hol |= holidays(v, y)
    # the first session of each pre-holiday run, and the trading session before it
    entry_dates: set[int] = set()
    for p in pre:
        d = date(p // 10000, p // 100 % 100, p % 100)
        prev = d - timedelta(days=1)
        while prev.weekday() >= 5 or prev in hol:
            prev -= timedelta(days=1)
        k = prev.year * 10000 + prev.month * 100 + prev.day
        if k not in pre:
            entry_dates.add(k)
    atr = _atr(df, atr_n).to_numpy(dtype=float)
    out: list[Signal] = []
    for d, i in _first_per_date(cm, ymd).items():
        if d in entry_dates and i < len(df) - 1:
            s = _sig(df, i, side, atr, stop_atr=stop_atr, rr=rr, hold_bars=hold_bars,
                     tag=f"pre_holiday_drift:{v}")
            if s is not None:
                out.append(s)
    return out


