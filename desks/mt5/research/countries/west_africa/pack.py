# --------------------------------------------------------------------------- the two calendars
#: FIVE COUNTRIES, TWO CALENDAR SYSTEMS RUNNING AT ONCE, AND BOTH MATTER. All five are Gregorian
#: for the civil year and all five carry the CHRISTIAN movable feasts (Easter Monday everywhere,
#: with Ascension and Whit Monday in the more Catholic three) AND the ISLAMIC feasts, because
#: Mali, Burkina, Guinea and Senegal are overwhelmingly Muslim and Cote d'Ivoire is genuinely
#: mixed. Easter is COMPUTED here from the Gregorian computus; the Islamic feasts are TYPED with
#: the authority that sights them, because no arithmetic rule reproduces a sighting and a wrong
#: rule is worse than an honest table (L1.28a).
def western_easter(gregorian_year: int) -> date:
    """Easter Sunday in the GREGORIAN computus (Meeus/Butcher). All five of these countries use
    the Western date -- unlike Ethiopia, whose Fasika runs on the Julian rule."""
    year = int(gregorian_year)
    a = year % 19
    b, c = divmod(year, 100)
    d, e = divmod(b, 4)
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = divmod(c, 4)
    ell = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * ell) // 451
    month = (h + ell - 7 * m + 114) // 31
    day = ((h + ell - 7 * m + 114) % 31) + 1
    return date(year, month, day)


def easter_monday(gregorian_year: int) -> date:
    """Lundi de Paques -- a public holiday in all five."""
    return western_easter(gregorian_year) + timedelta(days=1)


def ascension(gregorian_year: int) -> date:
    """Jeudi de l'Ascension, thirty-nine days after Easter. A public holiday in CI, BF and SN."""
    return western_easter(gregorian_year) + timedelta(days=39)


def whit_monday(gregorian_year: int) -> date:
    """Lundi de Pentecote, fifty days after Easter. A public holiday in CI and SN."""
    return western_easter(gregorian_year) + timedelta(days=50)


