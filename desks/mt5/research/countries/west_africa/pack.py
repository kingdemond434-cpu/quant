def cocoa_campaign(day: date) -> tuple[int, str]:
    """Which Ivorian cocoa campaign a day sits in, as (opening year, phase).

    The MAIN crop (campagne principale) opens on 1 October and runs to 31 March; the MID crop
    (campagne intermediaire) runs from 1 April to 30 September. A January session therefore
    belongs to the campaign that opened the PREVIOUS October, which is the single most common
    off-by-one in cocoa work.
    """
    if day.month >= 10:
        return day.year, "MAIN"
    if day.month <= 3:
        return day.year - 1, "MAIN"
    return day.year - 1, "MID"


