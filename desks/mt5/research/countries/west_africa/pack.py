def national_holidays(year: int) -> dict[date, str]:
    """EVERY closed day in the five jurisdictions, TAGGED with the countries that close.

    A union table, because this pack answers for five countries at once and a day that shuts
    Ouagadougou is an ordinary session in Abidjan. The tag is what keeps a study from treating a
    one-country closure as a regional one -- and in this bloc the asymmetry has teeth, because
    the BRVM keeps the IVORIAN calendar for all eight UEMOA members.
    """
    tagged: dict[date, list[str]] = {}
    names: dict[date, str] = {}
    for code, fn in JURISDICTION_HOLIDAY_FN.items():
        for day, name in fn(year).items():
            tagged.setdefault(day, []).append(code.upper())
            names.setdefault(day, name)
    out = {day: f"{names[day]} [{'+'.join(sorted(codes))}]" for day, codes in tagged.items()}
    for day, name in DECLARED_EVENTS.items():
        if day.year == year:
            out[day] = f"{out.get(day, '')} NOT A CLOSURE: {name}".strip()
    return dict(sorted(out.items()))


def market_holidays(year: int) -> dict[date, str]:
    """The weekday CLOSURES only. Two filters and both are load-bearing: a Saturday holiday costs
    no session (and none of the five substitutes it onto the Monday), and a DECLARED_EVENTS row
    is a dated fact rather than a closed market."""
    return {d: n for d, n in national_holidays(year).items()
            if d.weekday() < 5 and d not in DECLARED_EVENTS}


def is_market_holiday(day: date) -> bool:
    return day in market_holidays(day.year)


def closed_in(code: str, day: date) -> bool:
    """True when THIS jurisdiction's own calendar closes on this day."""
    fn = JURISDICTION_HOLIDAY_FN.get(str(code).lower())
    return day in fn(day.year) if fn is not None else False


def brvm_closed(day: date) -> bool:
    """True when the REGIONAL exchange is shut. It keeps the Ivorian calendar, so a Senegalese
    or Malian investor's market closes on Ivorian holidays and stays open on their own -- the
    single most useful calendar asymmetry in this pack."""
    return closed_in("ci", day) and day.weekday() < 5


def announced_dates(year: int) -> dict[date, str]:
    """Only the Islamic feasts that were ANNOUNCED. A PROJECTED row can be a day off in any of
    the five, and Senegal has celebrated Korite on two different days in the same week."""
