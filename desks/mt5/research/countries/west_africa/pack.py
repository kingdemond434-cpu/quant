def _words(text: str) -> list[str]:
    """The word tokens of a phrase, keeping every letter the five languages actually use --
    French accents, the Wolof and Manding open-e and open-o, the Fula and Manding hooked
    letters. A naive ASCII split would silently drop exactly the words that prove a query is
    native rather than English."""
    out: list[str] = []
    buf: list[str] = []
    for ch in str(text):
        if ch.isalpha() or ch == "'":
            buf.append(ch)
        elif buf:
            out.append("".join(buf))
            buf = []
    if buf:
        out.append("".join(buf))
    return out


def has_manding(text: str) -> bool:
    """True when a phrase carries Dioula or Bambara vocabulary. WORD-matched, because Manding is
    written in Latin script and a codepoint test cannot find it."""
    words = {w.lower() for w in _words(text)}
    return any(m.lower() in words for m in MANDING_MARKERS)


def has_wolof(text: str) -> bool:
    words = {w.lower() for w in _words(text)}
    return any(m.lower() in words for m in WOLOF_MARKERS)


def has_fula(text: str) -> bool:
    words = {w.lower() for w in _words(text)}
    return any(m.lower() in words for m in FULA_MARKERS)


def has_moore(text: str) -> bool:
    words = {w.lower() for w in _words(text)}
    return any(m.lower() in words for m in MOORE_MARKERS)


def has_french(text: str) -> bool:
    """True when a phrase is French rather than English.

    TWO TESTS AND THE ORDER MATTERS. A curated French token that is NOT also an English word is
    conclusive on its own; an accent is conclusive only when no other native marker is present,
    because Wolof writes `njëg` and `liggéey` with the same diacritics French uses and this pack
    must not file a Wolof query as a French one.
    """
    words = {w.lower() for w in _words(text)}
    if any(w in _FRENCH_WORDS for w in words):
        return True
    if any(ch in _FRENCH_ACCENTS for ch in str(text)):
        return not (has_wolof(text) or has_manding(text) or has_fula(text) or has_moore(text))
    return False


def has_native(text: str) -> bool:
    """True when a phrase is in ANY of the five languages this pack queries in."""
    return (has_french(text) or has_manding(text) or has_wolof(text) or has_fula(text)
            or has_moore(text))


def _terms(terminology: Mapping[str, Iterable[str]] | None = None) -> list[str]:
    rows = TERMINOLOGY if terminology is None else terminology
    return [t for group in rows.values() for t in group]


def french_terms(terminology: Mapping[str, Iterable[str]] | None = None) -> list[str]:
    return [t for t in _terms(terminology) if has_french(t)]


def manding_terms(terminology: Mapping[str, Iterable[str]] | None = None) -> list[str]:
    return [t for t in _terms(terminology) if has_manding(t)]


def wolof_terms(terminology: Mapping[str, Iterable[str]] | None = None) -> list[str]:
    return [t for t in _terms(terminology) if has_wolof(t)]


def fula_terms(terminology: Mapping[str, Iterable[str]] | None = None) -> list[str]:
    return [t for t in _terms(terminology) if has_fula(t)]


def moore_terms(terminology: Mapping[str, Iterable[str]] | None = None) -> list[str]:
    return [t for t in _terms(terminology) if has_moore(t)]


def term_count(terminology: Mapping[str, Iterable[str]] | None = None) -> int:
    """Distinct terms across every domain key of the terminology table."""
    return len(set(_terms(terminology)))


def _seq(values: Iterable[Any]) -> tuple[str, ...]:
    return tuple(str(v) for v in values)


