"""Tier S layer 16: closure worlds and agent-based worlds, and their join per certificate.

  closure  the market shut and reopened gapped, a session removed for a stretch, an instrument
           halted on stale prints (`libs/tiers/closure_worlds.py`)
  agents   paths generated by momentum, value, noise and liquidity agents
           (`libs/tiers/agent_worlds.py`)

Both families run inside `synthetic_regimes` like every other world (named, seeded, UNMEASURED
when they cannot touch the tape) and are joined per certificate by `tier_s.organ_worlds` the way
the swap world is.
"""
