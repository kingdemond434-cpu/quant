# ------------------------------------------------------------------ the TEMPORARY Black-Scholes
def test_bs_put_call_parity_and_gamma_is_the_pdf_not_the_cdf() -> None:
    S, K, T, sig, r, q = 100.0, 95.0, 0.4, 0.3, 0.03, 0.01
    c, p = oc._bs(S, K, T, sig, "C", r, q), oc._bs(S, K, T, sig, "P", r, q)
    assert c is not None and p is not None
    assert c["price"] - p["price"] == pytest.approx(S * math.exp(-q * T) - K * math.exp(-r * T),
                                                    abs=1e-10)
    d1 = (math.log(S / K) + (r - q + 0.5 * sig * sig) * T) / (sig * math.sqrt(T))
    pdf_gamma = math.exp(-q * T) * math.exp(-0.5 * d1 * d1) / math.sqrt(2 * math.pi) / (
        S * sig * math.sqrt(T))
    assert c["gamma"] == pytest.approx(pdf_gamma, rel=1e-12) == p["gamma"]
    # finite difference of delta confirms it; the Q-Fin seeded defect (cdf in place of pdf) does not
    h = 1e-3
    up, dn = oc._bs(S + h, K, T, sig, "C", r, q), oc._bs(S - h, K, T, sig, "C", r, q)
    assert up is not None and dn is not None
    fd = (up["delta"] - dn["delta"]) / (2 * h)
    assert c["gamma"] == pytest.approx(fd, rel=1e-5)
    cdf_gamma = math.exp(-q * T) * oc._ncdf(d1) / (S * sig * math.sqrt(T))
    assert abs(cdf_gamma - fd) > 0.01
    # the donor's put (K e^-rT N(d1) - S N(d2)) breaks parity; ours does not
    d2 = d1 - sig * math.sqrt(T)
    bad_put = K * math.exp(-r * T) * oc._ncdf(d1) - S * oc._ncdf(d2)
    assert abs(bad_put - p["price"]) > 1.0
    iv = oc._implied_vol(c["price"], S, K, T, "C", r, q)
    assert iv == pytest.approx(sig, abs=1e-6)
    assert oc._bs(S, K, 0.0, sig, "C") is None


