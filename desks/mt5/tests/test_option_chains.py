def test_pit_falls_back_to_receipt_and_rescales_percent_iv() -> None:
    doc = _doc()
    doc["timestamp"] = "2026-10-05 23:59:00"            # later than receipt: the tz is wrong
    got = oc.parse_chain(doc, etf="SPY", received_at=RECEIVED)
    assert got["knowable_basis"] == "bounded_by_receipt"
    assert got["knowable_at"] == got["received_at"] and "later than receipt" in got["pit_note"]
    doc = _doc()
    doc.pop("timestamp")
    for o in doc["data"]["options"]:
        o.pop("last_trade_time", None)
        if isinstance(o.get("iv"), float):
            o["iv"] = o["iv"] * 100.0
    got = oc.parse_chain(doc, etf="SPY", received_at=RECEIVED)
    assert got["knowable_basis"] == "bounded_by_receipt" and got["iv_unit"] == "percent_rescaled"
    assert max(c["iv"] for c in got["contracts"] if c["iv"]) < 1.0


