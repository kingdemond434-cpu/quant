# ------------------------------------------------------------------ the organ end to end
def _business_days(n: int, start: date = date(2024, 1, 1)) -> list[date]:
    out, d = [], start
    while len(out) < n:
        if d.weekday() < 5:
            out.append(d)
        d += timedelta(days=1)
    return out


def test_run_budget_lake_ledger_and_unmeasured_contracts(tmp_path: Path) -> None:
    calls: list[str] = []

    def fetcher(etf: str) -> tuple[Any, str]:
        calls.append(etf)
        return (_doc(), "OK") if etf == "SPY" else (None, "FETCH_FAILED: offline")

    reg = {"US500": {"symbol": "US500"}, "XAUUSD": {"symbol": "XAUUSD"}}
    closes = [(d.isoformat(), 100.0 + i) for i, d in enumerate(_business_days(30))]
    ledger = sc.SensorLedger(tmp_path / "sensors")
    kw: dict[str, Any] = {"fetcher": fetcher, "etfs": ["SPY", "GLD", "TLT"],
                          "data_dir": tmp_path / "oc", "registry": reg,
                          "closes_fn": lambda s, n: closes, "vol_index_fn": lambda t: {},
                          "lake_root": tmp_path / "lake", "contracts_root": tmp_path / "c",
                          "ledger": ledger, "report": tmp_path / "R.json", "emit_cells": False}
    doc = oc.run(now=RECEIVED, **kw)
    assert calls == ["SPY", "GLD", "TLT"]
    spy = doc["symbols"]["SPY"]
    assert spy["parse"]["status"] == "PARSED" and spy["lake"]["status"] == "WRITTEN"
    assert doc["symbols"]["TLT"]["mapping"]["status"] == "NOT_TRADEABLE_HERE"
    assert {c["verdict"] for c in doc["contracts"]} == {se.UNMEASURED}
    assert {tuple(c["cards"]) for c in doc["contracts"]} == {("QG-ADH-001",), ("QG-OT-005",)}
    assert doc["ledger"]["appended"] >= 4 and doc["ledger"]["refused"] == 0
    rows = ledger.rows("2026-10-05")
    assert all(r["attributes"]["measure"] == "Q" for r in rows)
    assert all(r["knowable_basis"] == "printed_stamp" for r in rows)
    assert list((tmp_path / "oc" / "SPY").glob("*.json.gz"))
    assert (tmp_path / "R.json").exists() and (tmp_path / "c" / "option_chains.json").exists()
    # the budget: nothing is fetched again inside six hours, everything after
    oc.run(now=RECEIVED + timedelta(hours=5), **kw)
    assert len(calls) == 3
    oc.run(now=RECEIVED + timedelta(hours=6, minutes=1), **kw)
    assert len(calls) == 6
    # dry run writes nothing
    before = sorted(p.name for p in (tmp_path / "oc").rglob("*"))
    oc.run(now=RECEIVED + timedelta(days=2), dry_run=True, **kw)
    assert sorted(p.name for p in (tmp_path / "oc").rglob("*")) == before


