# ------------------------------------------------------------------ the GAIN path, synthetic
def _gex_world(n: int, planted: bool, seed: int = 4
               ) -> tuple[list[dict[str, Any]], list[tuple[str, float]]]:
    rng = np.random.default_rng(seed)
    days = _business_days(n)
    neg = np.zeros(n, dtype=bool)
    for i in range(1, n):
        neg[i] = neg[i - 1] if rng.random() < 0.95 else not neg[i - 1]
    rows = [{"available_time": f"{d.isoformat()}T14:00:00+00:00", "gex": -1e9 if neg[i] else 1e9}
            for i, d in enumerate(days)]
    px, prev = [100.0, 100.5], 0.005
    for k in range(2, n):
        eps = rng.normal(0.0, 0.01)
        r = eps + (0.005 * math.copysign(1.0, prev) if planted and neg[k - 1] else 0.0)
        px.append(px[-1] * math.exp(r))
        prev = r
    return rows, [(d.isoformat(), p) for d, p in zip(days, px, strict=True)]


def test_gex_contract_shows_gain_on_a_planted_effect_and_not_on_noise() -> None:
    rows, closes = _gex_world(700, planted=True)
    got = oc.gex_continuation_contract(rows, closes, etf="SPY", symbol="US500")
    assert got["verdict"] == se.GAIN, got
    assert got["continuation_rate_gex_neg"] > got["continuation_rate_gex_pos"]
    assert got["continuation_diff_p_two_sided"] < 0.05
    rows0, closes0 = _gex_world(700, planted=False)
    assert oc.gex_continuation_contract(rows0, closes0, etf="SPY",
                                        symbol="US500")["verdict"] != se.GAIN
    short_rows, short_closes = _gex_world(120, planted=True)
    assert oc.gex_continuation_contract(short_rows, short_closes, etf="SPY",
                                        symbol="US500")["verdict"] == se.UNMEASURED


def _vol_world(n: int, informative: bool, seed: int = 8
               ) -> tuple[list[dict[str, Any]], list[tuple[str, float]], dict[str, float]]:
    rng = np.random.default_rng(seed)
    days = _business_days(n)
    lv = np.zeros(n)
    for i in range(1, n):
        lv[i] = 0.97 * lv[i - 1] + rng.normal(0.0, 0.12)
    sigma = 0.16 * np.exp(lv)
    px = [100.0]
    for i in range(1, n):
        px.append(px[-1] * math.exp(rng.normal(0.0, sigma[i] / math.sqrt(252.0))))
    rows = [{"available_time": f"{d.isoformat()}T14:00:00+00:00",
             "atm_iv_30d": (sigma[i] if informative else 0.16 * math.exp(rng.normal(0, 0.3))),
             "skew_90_110": rng.normal(0.05, 0.01), "pc_oi_ratio": rng.normal(1.2, 0.1)}
            for i, d in enumerate(days)]
    index = {d.isoformat(): 20.0 + rng.normal(0.0, 2.0) for d in days}   # an uninformative index
    return rows, [(d.isoformat(), p) for d, p in zip(days, px, strict=True)], index


def test_vol_forecast_contract_gain_when_the_chain_adds_and_not_otherwise() -> None:
    rows, closes, index = _vol_world(700, informative=True)
    got = oc.vol_forecast_contract(rows, closes, index, etf="GLD", symbol="XAUUSD",
                                   vol_index="^GVZ")
    assert got["verdict"] == se.GAIN and got["relative_reduction"] > 0.2, got
    rows0, closes0, index0 = _vol_world(700, informative=False)
    assert oc.vol_forecast_contract(rows0, closes0, index0, etf="GLD", symbol="XAUUSD",
                                    vol_index="^GVZ")["verdict"] == se.NO_GAIN
    assert oc.vol_forecast_contract(rows[:150], closes[:150], index, etf="GLD",
                                    symbol="XAUUSD", vol_index="^GVZ")["verdict"] == se.UNMEASURED
