# ONE-TIME INSTALL OF THE RELEASE AUTHORITY ON THE BOX (ops/release/authority/ONE_TIME_AUTHORISATION.md).
#
# zuck runs this ONCE, elevated, after reading the pack. It is the only step that creates the
# authority's identity, so no Claude session runs it. It:
#   1. creates the local account `quant-authority` (random password, never shown or stored);
#   2. makes C:\opt\authority (its clean LIVE checkout + key folder) and the attestations folder,
#      with ACLs: the key folder is quant-authority + SYSTEM only; attestations are written only
#      by quant-authority and read by Administrators (the gate); the bridge's non-admin account
#      can read neither the key nor write the attestations;
#   3. generates the Ed25519 signing key INSIDE the key folder, as quant-authority, and writes
#      only the PUBLIC key to C:\opt\audit_registry\authority.pub (Administrators-writable);
#   4. pins the root digest of the checkout to C:\opt\audit_registry\ROOT_PIN.json;
#   5. registers the scheduled task Quant-ReleaseAuthority (every 10 min, as quant-authority).
# It does NOT turn the path on: the gate ignores the authority until the machine env vars in
# step 6 of the pack are set, and it does not touch any GitHub setting.

[CmdletBinding()]
param(
    [string] $Repo = "kingdemond434-cpu/quant",
    [string] $Live = "claude/llm-auto-upgrade-verify-gcjac3",
    [string] $Home_ = "C:\opt\authority",
    [string] $Registry = "C:\opt\audit_registry",
    [string] $Python = "C:\Program Files\Python314\python.exe",
    [Parameter(Mandatory)] [string] $AppId,
    [Parameter(Mandatory)] [string] $InstallationId
)
$ErrorActionPreference = 'Stop'
$User = "quant-authority"
$Key = Join-Path $Home_ "key"
$Clone = Join-Path $Home_ "repo"
$Att = Join-Path $Registry "attestations"

if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw "run elevated"
}
Add-Type -AssemblyName System.Web
$pw = [System.Web.Security.Membership]::GeneratePassword(40, 8)
$sec = ConvertTo-SecureString $pw -AsPlainText -Force
if (-not (Get-LocalUser -Name $User -ErrorAction SilentlyContinue)) {
    New-LocalUser -Name $User -Password $sec -PasswordNeverExpires -AccountNeverExpires -Description "Release authority signer (no login rights needed)" | Out-Null
} else {
    Set-LocalUser -Name $User -Password $sec
}

foreach ($d in @($Home_, $Key, $Att)) { New-Item -ItemType Directory -Force -Path $d | Out-Null }
# key folder: quant-authority + SYSTEM only (not even Administrators can read it without taking ownership)
& icacls $Key /inheritance:r /grant:r "${User}:(OI)(CI)M" "SYSTEM:(OI)(CI)F" | Out-Null
# attestations: written by quant-authority, read by Administrators (the gate), nobody else
& icacls $Att /inheritance:r /grant:r "${User}:(OI)(CI)M" "SYSTEM:(OI)(CI)F" "Administrators:(OI)(CI)RX" | Out-Null
# the home: quant-authority modifies its checkout; Administrators read
& icacls $Home_ /inheritance:r /grant:r "${User}:(OI)(CI)M" "SYSTEM:(OI)(CI)F" "Administrators:(OI)(CI)RX" | Out-Null

if (-not (Test-Path (Join-Path $Clone ".git"))) {
    & git clone -q --no-checkout "https://github.com/$Repo.git" $Clone
}
& git -C $Clone fetch -q --no-tags origin "+refs/heads/${Live}:refs/remotes/origin/${Live}"
& git -C $Clone checkout -q -f --detach "origin/$Live"
& icacls $Clone /setowner $User /T /C /Q | Out-Null

# The key is generated by the authority's own account, inside its own folder.
$cred = New-Object System.Management.Automation.PSCredential($User, $sec)
$gen = @"
from cryptography.hazmat.primitives import serialization as s
from cryptography.hazmat.primitives.asymmetric import ed25519
import base64, pathlib
k = ed25519.Ed25519PrivateKey.generate()
pathlib.Path(r'$Key\authority.pem').write_bytes(k.private_bytes(s.Encoding.PEM, s.PrivateFormat.PKCS8, s.NoEncryption()))
pathlib.Path(r'$Home_\authority.pub').write_text(base64.b64encode(k.public_key().public_bytes(s.Encoding.Raw, s.PublicFormat.Raw)).decode())
"@
if (-not (Test-Path (Join-Path $Key "authority.pem"))) {
    $p = Start-Process -FilePath $Python -ArgumentList @("-I", "-c", $gen) -Credential $cred -Wait -PassThru -WindowStyle Hidden
    if ($p.ExitCode -ne 0) { throw "key generation failed ($($p.ExitCode))" }
}
Copy-Item -Force (Join-Path $Home_ "authority.pub") (Join-Path $Registry "authority.pub")
& icacls (Join-Path $Registry "authority.pub") /inheritance:r /grant:r "Administrators:F" "SYSTEM:F" "${User}:R" "Users:R" | Out-Null

& $Python -I (Join-Path $Clone "ops\release\authority\pin_root.py") --write (Join-Path $Registry "ROOT_PIN.json")
& icacls (Join-Path $Registry "ROOT_PIN.json") /inheritance:r /grant:r "Administrators:F" "SYSTEM:F" "${User}:R" | Out-Null

# the runner runs from a copy OUTSIDE the checkout, so a changed runner on LIVE never runs
$runner = Join-Path $Home_ "run_authority.ps1"
Copy-Item -Force (Join-Path $Clone "ops\release\authority\run_authority.ps1") $runner
$act = New-ScheduledTaskAction -Execute "powershell.exe" -Argument ("-NoProfile -ExecutionPolicy Bypass -File `"$runner`" -AppId $AppId -InstallationId $InstallationId -Python `"$Python`"")
$trg = New-ScheduledTaskTrigger -Once -At (Get-Date) -RepetitionInterval (New-TimeSpan -Minutes 10)
$set = New-ScheduledTaskSettingsSet -ExecutionTimeLimit (New-TimeSpan -Minutes 30) -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName "Quant-ReleaseAuthority" -Action $act -Trigger $trg -Settings $set -User $User -Password $pw -Force | Out-Null
$pw = $null
Write-Host "public key id:" (Get-Content (Join-Path $Registry "authority.pub"))
Write-Host "root pin:" (Get-Content (Join-Path $Registry "ROOT_PIN.json"))
Write-Host "Now copy the authority App's private key into $Key\app.pem (see the pack, step 3)."
