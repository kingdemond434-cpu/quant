_LIBRARIES: tuple[str, ...] = ("gtja191", "alpha158", "alpha360")
_DIALECT: dict[str, str] = {"gtja191": "gtja", "alpha158": "qlib", "alpha360": "qlib"}

#: Fields an MT5 bar carries, as `formula_ops` panel keys.
_MT5_FIELDS: frozenset[str] = frozenset({"open", "high", "low", "close", "volume"})


@dataclass(frozen=True)
class Formula:
    library: str
    fid: str                  #: the publication's own id: "alpha001", "KMID", "CLOSE59"
    text: str                 #: the formula as published (dialect syntax)
    source: str
    note: str = ""
    #: a reason the printed text cannot be evaluated at all (it is still listed and counted)
    malformed: str = ""

    @property
    def key(self) -> str:
        """The stable identity used in the grammar's `["lib", key]` node and in cell ids."""
        return f"{self.library}_{self.fid}"

    @property
    def dialect(self) -> str:
        return _DIALECT[self.library]

    def fields(self) -> frozenset[str]:
        if self.malformed:
            return frozenset()
        return frozenset(fo.required_fields(self.text, self.dialect))

    def missing(self) -> list[str]:
        return sorted(self.fields() - _MT5_FIELDS)

    @property
    def status(self) -> str:
        return "NONTESTABLE" if self.malformed or self.missing() else "TESTABLE"

    def why_not(self) -> str:
        if self.malformed:
            return f"MALFORMED: {self.malformed}"
        miss = self.missing()
        return f"MISSING_FIELD: {', '.join(miss)} not on an MT5 feed" if miss else ""

    @property
    def needs_panel(self) -> bool:
        return not self.malformed and fo.needs_panel(self.text, self.dialect)

    @property
    def volume_proxy(self) -> str | None:
        return "tick" if "volume" in self.fields() else None

    def as_dict(self) -> dict[str, Any]:
        return {"key": self.key, "library": self.library, "id": self.fid, "text": self.text,
                "dialect": self.dialect, "status": self.status, "why_not": self.why_not(),
                "cross_sectional": self.needs_panel, "volume_proxy": self.volume_proxy,
                "fields": sorted(self.fields()), "source": self.source, "note": self.note}


