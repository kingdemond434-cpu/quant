def _alpha360() -> list[Formula]:
    """Alpha360DL.get_feature_config: 6 fields x 60 lags, the loader's own loops."""
    src = _QLIB_SOURCE.format(cls="Alpha360DL")
    out: list[Formula] = []
    for field in ("close", "open", "high", "low", "vwap"):
        for i in range(59, 0, -1):
            out.append(Formula("alpha360", f"{field.upper()}{i}", f"Ref(${field}, {i})/$close",
                               src))
        out.append(Formula("alpha360", f"{field.upper()}0", f"${field}/$close", src))
    for i in range(59, 0, -1):
        out.append(Formula("alpha360", f"VOLUME{i}", f"Ref($volume, {i})/($volume+1e-12)", src))
    out.append(Formula("alpha360", "VOLUME0", "$volume/($volume+1e-12)", src))
    return out


@lru_cache(maxsize=1)
def catalog() -> dict[str, Formula]:
    """key -> Formula over all three libraries, in publication order."""
    rows = _gtja() + _alpha158() + _alpha360()
    out: dict[str, Formula] = {}
    for f in rows:
        if f.key in out:
            raise ValueError(f"duplicate formula key {f.key}")
        out[f.key] = f
    return out


def libraries() -> tuple[str, ...]:
    """The three libraries, in publication order."""
    return _LIBRARIES


def get(key: str) -> Formula | None:
    return catalog().get(str(key))


def by_library(library: str) -> list[Formula]:
    return [f for f in catalog().values() if f.library == library]


def census() -> dict[str, Any]:
    """Per library: published, implemented (TESTABLE on MT5), nontestable by reason."""
    out: dict[str, Any] = {}
    for lib in _LIBRARIES:
        rows = by_library(lib)
        why: dict[str, int] = {}
        for f in rows:
            if f.status != "TESTABLE":
                k = f.why_not().split(":")[0] + ":" + (",".join(f.missing()) or "text")
                why[k] = why.get(k, 0) + 1
        out[lib] = {"published": len(rows),
                    "testable": sum(1 for f in rows if f.status == "TESTABLE"),
                    "nontestable": sum(1 for f in rows if f.status != "TESTABLE"),
                    "nontestable_by_reason": dict(sorted(why.items())),
                    "cross_sectional": sum(1 for f in rows
                                           if f.status == "TESTABLE" and f.needs_panel),
                    "volume_proxy_tick": sum(1 for f in rows
                                             if f.status == "TESTABLE" and f.volume_proxy),
                    "source": rows[0].source if rows else ""}
    return out


def evaluate(key: str, fields: dict[str, Any]) -> Any:
    """The formula as a panel DataFrame on `fields` (formula_ops panel keys). Raises
    MissingField / FormulaError exactly as the engine does; never approximates a field."""
    f = get(key)
    if f is None:
        raise fo.FormulaError(f"unknown formula {key!r}")
    if f.malformed:
        raise fo.FormulaError(f"{key} is not computable as printed: {f.malformed}")
    return fo.Evaluator(fields, f.dialect).evaluate(f.text)
